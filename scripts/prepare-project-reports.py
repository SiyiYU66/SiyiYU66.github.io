"""Prepare faithful page previews and byte-identical, streamed PDF downloads.

Run pdftoppm -png -scale-to 1600 first. The original PDFs are NOT re-encoded:
8 MiB parts keep each deployed static asset within the hosting size limit.
"""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageOps

ROOT = Path(__file__).resolve().parent.parent
REPORTS = {
    "sedan": ("slow-forms", "Sedan Redesign", "Siyi_Yu_Thermofluids_Sedan.pdf"),
    "battery": ("a-quiet-place", "Battery Cold Plate", "Siyi_Yu_Thermofluids_Battery.pdf"),
    "sustainable": ("soft-signals", "Aircraft Seat", "Siyi_Yu_Sustainable_Design_Engineering.pdf"),
    "fea": ("common-ground", "Running Blade FEA", "FEA_Siyi_Yu.pdf"),
}
PART_SIZE = 8 * 1024 * 1024


def existing_export(path):
    """A selected report update must leave the other report records untouched."""
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8").split(" = ", 1)[1].strip().removesuffix(";"))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--pdf-directory", required=True, type=Path)
    parser.add_argument("--render-directory", required=True, type=Path)
    parser.add_argument("--review-directory", required=True, type=Path)
    parser.add_argument("--reports", nargs="+", choices=REPORTS, default=["sedan", "battery"],
                        help="Reports to generate; existing records for other reports are preserved.")
    args = parser.parse_args()
    args.review_directory.mkdir(parents=True, exist_ok=True)
    downloads = existing_export(ROOT / "worker" / "report-manifest.js")
    previews = existing_export(ROOT / "dist" / "report-previews.js")
    for key in args.reports:
        project_id, title, filename = REPORTS[key]
        folder = ROOT / "assets" / "projects" / project_id / "report"
        (folder / "parts").mkdir(parents=True, exist_ok=True)
        prefix = f"/assets/projects/{project_id}/report"
        pages, thumbs = [], []
        for number, source in enumerate(sorted((args.render_directory / key).glob("page-*.png")), 1):
            image = Image.open(source).convert("RGB")
            for width, suffix in [(1280, ""), (640, "-small")]:
                resized = image.resize((width, round(image.height * width / image.width)), Image.Resampling.LANCZOS)
                resized.save(folder / f"page-{number:02d}{suffix}.webp", "WEBP", quality=92, method=6)
            pages.append({
                "src": f"{prefix}/page-{number:02d}.webp",
                "smallSrc": f"{prefix}/page-{number:02d}-small.webp",
                "width": 1280, "height": round(image.height * 1280 / image.width),
                "caption": f"{title} report · Page {number:02d}", "page": number,
            })
            thumb = ImageOps.contain(image, (360, 255))
            tile = Image.new("RGB", (384, 289), "#e8e6e1")
            tile.paste(thumb, ((384-thumb.width)//2, 8))
            ImageDraw.Draw(tile).text((12, 268), f"{title} / {number:02d}", fill="#161616")
            thumbs.append(tile)
        if not pages:
            raise RuntimeError(f"No rendered pages for {key}")
        sheet = Image.new("RGB", (384 * 4, 289 * ((len(thumbs)+3)//4)), "#ccc9c4")
        for i, tile in enumerate(thumbs):
            sheet.paste(tile, ((i % 4) * 384, (i // 4) * 289))
        sheet.save(args.review_directory / f"{key}-report-contact-sheet.jpg", quality=92)

        original = args.pdf_directory / filename
        digest, parts, total = hashlib.sha256(), [], 0
        with original.open("rb") as stream:
            while chunk := stream.read(PART_SIZE):
                name = f"part-{len(parts)+1:02d}.bin"
                (folder / "parts" / name).write_bytes(chunk)
                digest.update(chunk)
                total += len(chunk)
                parts.append({"path": f"{prefix}/parts/{name}", "size": len(chunk)})
        href = f"/downloads/{filename}"
        previous_href = previews.get(key, {}).get("href")
        if previous_href and previous_href != href:
            downloads.pop(previous_href, None)
        downloads[href] = {"filename": filename, "size": total, "sha256": digest.hexdigest(), "parts": parts}
        previews[key] = {"title": title, "filename": filename, "href": href, "pages": pages}
        print(f"{title}: {len(pages)} pages, {total:,} original bytes, {len(parts)} parts, SHA256 {digest.hexdigest()}")

    (ROOT / "worker" / "report-manifest.js").write_text(
        "// Generated by scripts/prepare-project-reports.py. Original PDF bytes, unchanged.\n"
        "export const reports = " + json.dumps(downloads, indent=2) + ";\n", encoding="utf-8")
    (ROOT / "dist" / "report-previews.js").write_text(
        "// Generated page images; keep the download originals separate from web previews.\n"
        "export const reportPreviews = " + json.dumps(previews, indent=2, ensure_ascii=False) + ";\n", encoding="utf-8")


if __name__ == "__main__":
    main()
